import { createContext, useCallback, useContext, useEffect, useRef, useState, type ReactNode } from 'react';
import type { AppData } from '../types';
import { loadAppData, saveAppData } from '../services/storage';
import { applyServerChanges, hotelRequest, serverChanges, serverInitial, usesHotelServer, type ServerChange, type ServerReply } from '../services/hotelServer';

type Updater = (current: AppData) => AppData;
type AppDataContextValue = { data: AppData; updateData: (updater: Updater) => AppData; refreshData: () => void; replaceServerData: (reply: ServerReply) => void; serverStatus: 'ready' | 'saving' | 'error'; serverError: string };
const AppDataContext = createContext<AppDataContextValue | null>(null);

export function AppDataProvider({ children }: { children: ReactNode }) {
  const [data, setData] = useState<AppData>(() => serverInitial()?.data ?? loadAppData());
  const dataRef = useRef(data); dataRef.current = data;
  const revision = useRef(serverInitial()?.revision ?? 0);
  const pending = useRef<ServerChange[][]>([]);
  const busy = useRef(false);
  const generation = useRef(0);
  const [serverStatus, setServerStatus] = useState<'ready' | 'saving' | 'error'>('ready');
  const [serverError, setServerError] = useState('');
  const replaceServerData = useCallback((reply: ServerReply) => {
    generation.current++; pending.current = []; revision.current = reply.revision;
    dataRef.current = reply.data; setData(reply.data); setServerStatus('ready'); setServerError('');
  }, []);
  const drain = useCallback(async (): Promise<void> => {
    if (busy.current) return;
    busy.current = true;
    const currentGeneration = generation.current;
    setServerStatus('saving');
    try {
      while (pending.current.length && currentGeneration === generation.current) {
        const reply = await hotelRequest('state', 'PATCH', { revision: revision.current, changes: pending.current[0] });
        if (currentGeneration !== generation.current) break;
        revision.current = reply.revision; pending.current.shift();
        let visible = reply.data;
        for (const changes of pending.current) visible = applyServerChanges(visible, changes);
        dataRef.current = visible; setData(visible);
      }
      if (currentGeneration === generation.current) { setServerStatus('ready'); setServerError(''); }
    } catch (cause) {
      if (currentGeneration === generation.current) {
        pending.current = [];
        const message = cause instanceof Error ? cause.message : 'Serverga saqlanmadi.';
        try { const reply = await hotelRequest('session'); revision.current = reply.revision; dataRef.current = reply.data; setData(reply.data); } catch { /* Retain an explicit unsaved error while offline. */ }
        setServerError(`${message} O‘zgarish saqlanmadi; server nusxasini tekshiring.`); setServerStatus('error');
      }
    } finally { busy.current = false; if (pending.current.length) void drain(); }
  }, []);
  const updateData = useCallback((updater: Updater) => {
    const previous = dataRef.current;
    const next = updater(previous);
    if (usesHotelServer()) {
      const changes = serverChanges(previous, next);
      // Audit/visit and newly-created notifications are generated by the server.
      const writable = changes.filter((change) => change.collection !== 'notifications' || previous.notifications.some((item) => item.id === change.id));
      if (!writable.length) return previous;
      dataRef.current = next; setData(next); pending.current.push(writable); void drain();
    } else { dataRef.current = next; setData(next); saveAppData(next); }
    return next;
  }, [drain]);
  const refreshData = useCallback(() => {
    if (usesHotelServer()) {
      const session = generation.current;
      const version = revision.current;
      if (!busy.current) void hotelRequest('session').then((reply) => { if (!busy.current && !pending.current.length && session === generation.current && version === revision.current) replaceServerData(reply); }).catch((cause) => { setServerError(String(cause)); setServerStatus('error'); });
      return;
    }
    const latest = loadAppData(); dataRef.current = latest; setData(latest);
  }, [replaceServerData]);
  useEffect(() => {
    if (usesHotelServer()) {
      const timer = window.setInterval(() => { if (!busy.current && !pending.current.length && document.visibilityState === 'visible') refreshData(); }, 15000);
      return () => window.clearInterval(timer);
    }
    const onStorage = (event: StorageEvent) => { if (event.key === null || event.key === 'origin-hotel-app-data-v1') refreshData(); };
    window.addEventListener('storage', onStorage);
    return () => window.removeEventListener('storage', onStorage);
  }, [refreshData]);
  useEffect(() => {
    if (!usesHotelServer()) return;
    const warn = (event: BeforeUnloadEvent) => { if (busy.current || pending.current.length) event.preventDefault(); };
    window.addEventListener('beforeunload',warn); return () => window.removeEventListener('beforeunload',warn);
  }, []);
  return <AppDataContext.Provider value={{ data, updateData, refreshData, replaceServerData, serverStatus, serverError }}>{children}</AppDataContext.Provider>;
}
export function useAppData() { const context = useContext(AppDataContext); if (!context) throw new Error('useAppData must be used inside AppDataProvider'); return context; }
